#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const read = async (file) => JSON.parse(await readFile(new URL(`../${file}`, import.meta.url), 'utf8'));
const output = async (file, text) => writeFile(new URL(`../${file}`, import.meta.url), text);
const ca = await read('content/questions/california/scenarios.json');
const caFile = 'content/questions/california/QUESTIONS.md';
const nyFile = 'content/questions/new-york/NY_Ethics_Email_Scenarios.md';
const caUrl = 'https://www.calbar.ca.gov/legal-professionals/rules/rules-professional-conduct/current-rules-professional-conduct';
const nyUrl = 'https://www.nycourts.gov/rules/amendments-joint-rules-departments-appellate-division';
const metadata = (jurisdiction, localSourceFile, sourceUrl) => ({
  jurisdiction, sourceType: jurisdiction === 'California' ? 'california-style' : 'new-york-style',
  sourceNote: `Unofficial ${jurisdiction} educational practice. Source check: September 27, 2026. Not official bar-exam questions or legal advice.`,
  sourceChecked: '2026-09-27', localSourceFile, sourceUrl,
  sourceLabel: `${jurisdiction} questions and answer key`,
  officialSourceLabel: `${jurisdiction} rules and amendments`,
});
const reward = (difficulty) => difficulty === 1 ? 35 : difficulty === 2 ? 45 : 60;
const california = ca.map(({ answers, correct, ...s }) => ({
  ...s, ...metadata('California', caFile, caUrl), gold: reward(s.difficulty),
  choices: answers.map((text, i) => ({ text, grade: i === correct ? 'correct' : 'wrong',
    ...(i === correct ? {} : { why: `${s.rule}: ${s.explanation}` }) })),
}));

// New York's numbered email pack has an explicit four-column answer key.
const markdown = await readFile(new URL(`../${nyFile}`, import.meta.url), 'utf8');
const keys = new Map([...markdown.matchAll(/^\|\s*(\d+)\s*\|\s*([A-D])\s*\|\s*([^|]+)\|\s*([^|]+)\|$/gm)]
  .map(m => [+m[1], { letter: m[2], rule: m[3].trim(), explanation: m[4].trim() }]));
const headings = [...markdown.matchAll(/^## (\d+)\. (.+)$/gm)];
const newYork = headings.map((heading, i) => {
  const section = markdown.slice(heading.index, headings[i + 1]?.index ?? markdown.indexOf('# Answer Key'));
  const from = section.match(/^> \*\*From:\*\* (.+)$/m)?.[1]?.split(', ');
  const subject = section.match(/^> \*\*Subject:\*\* (.+)$/m)?.[1];
  const body = section.split('\n').filter(line => /^>/.test(line) && !/^> \*\*/.test(line))
    .map(line => line.replace(/^> ?/, '')).filter(Boolean).join('\n\n');
  const choices = [...section.matchAll(/^- \*\*([A-D])\.\*\* (.+)$/gm)];
  const key = keys.get(+heading[1]);
  assert.ok(from?.length && subject && body && key, `Missing metadata or key in NY ${heading[1]}`);
  assert.equal(choices.length, 4);
  const difficulty = i < 4 ? 1 : i < 14 ? 2 : 3;
  return { id: `ny_email_${heading[1]}_${heading[2].toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/_$/, '')}`,
    ...metadata('New York', nyFile, nyUrl), difficulty, gold: reward(difficulty),
    from: from[0], role: from.slice(1).join(', '), subject, body,
    rule: key.rule, explanation: key.explanation,
    choices: choices.map(m => ({ text: m[2], grade: m[1] === key.letter ? 'correct' : 'wrong',
      ...(m[1] === key.letter ? {} : { why: `${key.rule}: ${key.explanation}` }) })),
  };
});
const shorts = await read('content/questions/new-york/short-scenarios.json');
newYork.push(...shorts.map(s => ({ ...s, ...metadata('New York', 'content/questions/new-york/SHORT-QUESTIONS.md', nyUrl) })));
assert.equal(california.length, 20); assert.equal(newYork.length, 33);
for (const s of [...california, ...newYork]) {
  assert.equal(s.choices.filter(c => c.grade === 'correct').length, 1, s.id);
  assert.ok(s.choices.every(c => c.text && (c.grade === 'correct' || c.why)), s.id);
}
await output('js/data/state-questions.js', `// Generated by npm run states:build. Edit content/questions sources.\nexport const CALIFORNIA_SCENARIOS = ${JSON.stringify(california, null, 2)};\n\nexport const NEW_YORK_SCENARIOS = ${JSON.stringify(newYork, null, 2)};\n`);
const reviewDoc = (title, list) => `# ${title}\n\nUnofficial educational practice. Source check: September 27, 2026.\nSee [source review](SOURCES.md). Generated from the JSON authoring source; edit that source, then run \`npm run states:build\`.\n\n` + list.map((s, i) => `## ${i + 1}. ${s.subject}\n\nFrom: ${s.from}, ${s.role}\n\n${s.body}\n\n${s.choices.map((c, n) => `${String.fromCharCode(65 + n)}. ${c.text}`).join('\n\n')}\n\n**Answer: ${String.fromCharCode(65 + s.choices.findIndex(c => c.grade === 'correct'))}.** ${s.explanation}\n\nAuthority: ${s.rule}.\n`).join('\n');
await output(caFile, reviewDoc('California ethics questions', california));
await output('content/questions/new-york/SHORT-QUESTIONS.md', reviewDoc('New York short BarMail questions', shorts));
console.log(`Built ${california.length} California and ${newYork.length} New York questions.`);
